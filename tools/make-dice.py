def crop_resize(w, h, rgb, box, size):
    """Crop `box` (fractions of the source) and bilinear-resample it to size x size."""
    x0, y0, x1, y1 = (box[0] * w, box[1] * h, box[2] * w, box[3] * h)
    out = bytearray(size * size * 3)
    for j in range(size):
        sy = y0 + (y1 - y0) * (j + 0.5) / size - 0.5
        j0 = max(0, min(h - 1, int(math.floor(sy)))); j1 = min(h - 1, j0 + 1)
        fy = max(0.0, min(1.0, sy - j0))
        for i in range(size):
            sx = x0 + (x1 - x0) * (i + 0.5) / size - 0.5
            i0 = max(0, min(w - 1, int(math.floor(sx)))); i1 = min(w - 1, i0 + 1)
            fx = max(0.0, min(1.0, sx - i0))
            o = (j * size + i) * 3
            for c in range(3):
                a = rgb[(j0 * w + i0) * 3 + c] * (1 - fx) + rgb[(j0 * w + i1) * 3 + c] * fx
                b = rgb[(j1 * w + i0) * 3 + c] * (1 - fx) + rgb[(j1 * w + i1) * 3 + c] * fx
                out[o + c] = int(a * (1 - fy) + b * fy + 0.5)
    return out


def rotate90(size, img, turns):
    """Rotate a square image by `turns` quarter-turns, so six faces cut from one swatch
    don't read as six photocopies of the same grain."""
    turns %= 4
    if turns == 0:
        return bytearray(img)
    out = bytearray(len(img))
    for y in range(size):
        for x in range(size):
            if turns == 1:
                sx, sy = y, size - 1 - x
            elif turns == 2:
                sx, sy = size - 1 - x, size - 1 - y
            else:
                sx, sy = size - 1 - y, x
            d, s = (y * size + x) * 3, (sy * size + sx) * 3
            out[d:d + 3] = img[s:s + 3]
    return out


def median_rgb(size, img):
    ch = []
    for c in range(3):
        vals = sorted(img[c::3])
        ch.append(vals[len(vals) // 2])
    return tuple(ch)


def stamp_pip(size, img, cx, cy, r, dark):
    """A pip, drawn as a recess rather than a sticker: the disc is darkened, its upper-left rim
    darker still and its lower-right rim lifted, which is what sells a carved dot under the
    board's single soft key light. Coverage is analytic, so the edge is clean at any radius."""
    x0, x1 = max(0, int(cx - r - 2)), min(size - 1, int(cx + r + 2))
    y0, y1 = max(0, int(cy - r - 2)), min(size - 1, int(cy + r + 2))
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            dx, dy = x + 0.5 - cx, y + 0.5 - cy
            d = math.hypot(dx, dy)
            cov = max(0.0, min(1.0, (r - d) + 0.5))     # 1px analytic feather
            if cov <= 0:
                continue
            # -1 at the upper-left rim, +1 at the lower-right; 0 across the flat middle
            rim = max(0.0, (d / r) - 0.55) / 0.45
            lean = (dx + dy) / (r * 1.4142) * rim
            shade = 1.0 + 0.45 * lean
            o = (y * size + x) * 3
            for c in range(3):
                tgt = max(0, min(255, int(dark[c] * shade)))
                img[o + c] = int(img[o + c] * (1 - cov) + tgt * cov + 0.5)


def build_atlas(face, cell, pip_r, pip_gap, dark):
    """Six faces into a 3x2 atlas. Value v occupies cell v-1, left to right, top to bottom."""
    aw, ah = cell * 3, cell * 2
    atlas = bytearray(aw * ah * 3)
    for name, value, _r, _u in FACES:
        base = rotate90(cell, face, value - 1)
        step = cell * pip_gap
        mid = cell / 2.0
        for slot in PIPS[value]:
            cx = mid + (slot % 3 - 1) * step
            cy = mid + (slot // 3 - 1) * step
            stamp_pip(cell, base, cx, cy, cell * pip_r, dark)
        col, row = (value - 1) % 3, (value - 1) // 3
        for y in range(cell):
            d = ((row * cell + y) * aw + col * cell) * 3
            atlas[d:d + cell * 3] = base[y * cell * 3:(y + 1) * cell * 3]
    return aw, ah, atlas


# ---------------------------------------------------------------------------------------------
# Geometry: a rounded cube, one grid per face
# ---------------------------------------------------------------------------------------------
def rounded_box(half, radius, seg):
    """Positions, normals, UVs and indices for a rounded cube of half-extent `half`.

    The roundover comes from the standard clamp identity: for a point p on the cube, take
    c = clamp(p, -(half-radius), +(half-radius)) and push it back out by the radius along
    p-c. Two useful things fall out of it for free. Adjacent faces land on exactly the same
    positions and normals along their shared bevel, so the cube is watertight and shades
    smoothly without any welding; and each face keeps its own planar UV, so a pip painted
    at the centre of a face texture arrives at the centre of a flat face, never smeared
    around a corner. The bevel eats only the outer border of each cell, which is bare
    material by construction.
    """
    pos, nrm, uv, idx = [], [], [], []
    inner = half - radius
    for _name, value, r, u in FACES:
        n = (r[1] * u[2] - r[2] * u[1], r[2] * u[0] - r[0] * u[2], r[0] * u[1] - r[1] * u[0])
        col, row = (value - 1) % 3, (value - 1) // 3
        first = len(pos)
        for j in range(seg + 1):
            t = -1.0 + 2.0 * j / seg
            for i in range(seg + 1):
                s = -1.0 + 2.0 * i / seg
                p = [n[k] * half + r[k] * s * half + u[k] * t * half for k in range(3)]
                c = [max(-inner, min(inner, v)) for v in p]
                d = [p[k] - c[k] for k in range(3)]
                ln = math.sqrt(sum(v * v for v in d)) or 1.0
                d = [v / ln for v in d]
                pos.append(tuple(c[k] + d[k] * radius for k in range(3)))
                nrm.append(tuple(d))
                # glTF UV origin is top-left, so v runs down: t=+1 is the top of the cell.
                fu, fv = (s + 1.0) / 2.0, (1.0 - t) / 2.0
                uv.append(((col + fu) / 3.0, (row + fv) / 2.0))
        for j in range(seg):
            for i in range(seg):
                a = first + j * (seg + 1) + i
                b, cc, dd = a + 1, a + seg + 2, a + seg + 1
                idx += [a, b, cc, a, cc, dd]      # CCW from outside: (r, u, n) is right-handed
    return pos, nrm, uv, idx


