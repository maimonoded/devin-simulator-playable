#!/usr/bin/env python3
"""Build the board's die asset: assets/dice/models/die.glb, plus the face atlas it bakes in.

WHY THIS IS BUILT RATHER THAN RECONSTRUCTED
-------------------------------------------
Every other 3D asset here comes back from Scenario's image-to-3D step. A die can't. Image-to-3D
sees one render, so it sees at most three faces; the other three are invented, and the pip counts
it invents are wrong roughly as often as not. Worse, nothing in that pipeline knows that a die's
faces are not independent — opposite faces must sum to 7, and the three faces around a corner
must run counter-clockwise for a right-handed die. A generator has no reason to honour either.

So the work is split along the line of what is *countable*:

    Scenario supplies the SURFACE  — assets/dice/raw/face-src.png, one blank face in the
                                     board's style, generated by the same flux + LoRA pair
                                     the tiles use, so the die matches the board.
    This tool supplies the COUNTS  — the six pip layouts, where they sit, which value lands
                                     on which face, and the geometry underneath.

The result is verified from the pixels, not from the table that drew them: --check re-reads the
finished atlas, counts blobs per face, and fails if any face doesn't hold the pips it claims.

Zero dependencies, like tools/normalize-env.py — PNG in and out through zlib.

    python3 tools/make-dice.py                    # build from the default paths
    python3 tools/make-dice.py --check            # build, then verify the atlas by counting pips
"""

import argparse
import math
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

# ---------------------------------------------------------------------------------------------
# The die itself
# ---------------------------------------------------------------------------------------------
# Faces, in the order the engine's axes run: +X right, +Y up, +Z toward the viewer.
#
# The values are not a free choice. A Western die is right-handed: with 1 up and 2 facing you,
# 3 is on the RIGHT. Combined with opposite-faces-sum-to-7 that fixes all six at once, and the
# --check pass asserts both rules rather than trusting this table.
#
#   axis      value   right (u+)      up (v+)
FACES = [
    ("+X",  3, (0, 0, -1), (0, 1, 0)),
    ("-X",  4, (0, 0,  1), (0, 1, 0)),
    ("+Y",  1, (1, 0,  0), (0, 0, -1)),
    ("-Y",  6, (1, 0,  0), (0, 0,  1)),
    ("+Z",  2, (1, 0,  0), (0, 1, 0)),
    ("-Z",  5, (-1, 0, 0), (0, 1, 0)),
]

# Pip positions on a 3x3 grid, column-major cell ids:
#   0 1 2
#   3 4 5
#   6 7 8
PIPS = {
    1: [4],
    2: [0, 8],
    3: [0, 4, 8],
    4: [0, 2, 6, 8],
    5: [0, 2, 4, 6, 8],
    6: [0, 2, 3, 5, 6, 8],
}


# ---------------------------------------------------------------------------------------------
# PNG, both directions. Only what this tool actually meets: 8-bit, non-interlaced, grey/RGB/RGBA.
# ---------------------------------------------------------------------------------------------
def png_read(path):
    """-> (w, h, bytearray of RGB triples)."""
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG")
    pos, idat, w, h, ct = 8, [], None, None, None
    while pos + 8 <= len(data):
        ln = int.from_bytes(data[pos:pos + 4], "big")
        typ = data[pos + 4:pos + 8]
        chunk = data[pos + 8:pos + 8 + ln]
        pos += 12 + ln
        if typ == b"IHDR":
            w, h, bd, ct, _comp, _filt, inter = struct.unpack(">IIBBBBB", chunk)
            if bd != 8 or inter or ct not in (0, 2, 6):
                sys.exit(f"{path}: need an 8-bit non-interlaced grey/RGB/RGBA PNG "
                         f"(got bit depth {bd}, colour type {ct}, interlace {inter})")
        elif typ == b"IDAT":
            idat.append(chunk)
        elif typ == b"IEND":
            break
    raw = zlib.decompress(b"".join(idat))

    nch = {0: 1, 2: 3, 6: 4}[ct]
    stride = w * nch
    prev = bytearray(stride)
    rgb = bytearray(w * h * 3)
    p = 0
    for y in range(h):
        f = raw[p]; p += 1
        line = bytearray(raw[p:p + stride]); p += stride
        if f == 1:
            for i in range(nch, stride):
                line[i] = (line[i] + line[i - nch]) & 255
        elif f == 2:
            for i in range(stride):
                line[i] = (line[i] + prev[i]) & 255
        elif f == 3:
            for i in range(stride):
                a = line[i - nch] if i >= nch else 0
                line[i] = (line[i] + ((a + prev[i]) >> 1)) & 255
        elif f == 4:
            for i in range(stride):
                a = line[i - nch] if i >= nch else 0
                c = prev[i - nch] if i >= nch else 0
                b = prev[i]
                est = a + b - c
                da, db, dc = abs(est - a), abs(est - b), abs(est - c)
                pred = a if (da <= db and da <= dc) else (b if db <= dc else c)
                line[i] = (line[i] + pred) & 255
        elif f != 0:
            sys.exit(f"{path}: unknown scanline filter {f}")
        o = y * w * 3
        if nch == 3:
            rgb[o:o + w * 3] = line
        elif nch == 1:
            for x in range(w):
                rgb[o + x * 3] = rgb[o + x * 3 + 1] = rgb[o + x * 3 + 2] = line[x]
        else:
            for x in range(w):
                rgb[o + x * 3:o + x * 3 + 3] = line[x * 4:x * 4 + 3]
        prev = line
    return w, h, rgb


def png_write(path, w, h, rgb):
    raw = bytearray()
    for y in range(h):
        raw.append(0)                                  # filter 0; the atlas compresses fine flat
        raw += rgb[y * w * 3:(y + 1) * w * 3]

    def chunk(typ, payload):
        return (struct.pack(">I", len(payload)) + typ + payload
                + struct.pack(">I", zlib.crc32(typ + payload) & 0xFFFFFFFF))

    blob = (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
            + chunk(b"IEND", b""))
    open(path, "wb").write(blob)
    return blob


