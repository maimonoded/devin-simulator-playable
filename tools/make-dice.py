def write_glb(path, pos, nrm, uv, idx, png):
    import json

    def pad(b):
        return b + b"\x00" * ((4 - len(b) % 4) % 4)

    b_pos = struct.pack(f"<{len(pos) * 3}f", *[c for v in pos for c in v])
    b_nrm = struct.pack(f"<{len(nrm) * 3}f", *[c for v in nrm for c in v])
    b_uv = struct.pack(f"<{len(uv) * 2}f", *[c for v in uv for c in v])
    b_idx = struct.pack(f"<{len(idx)}H", *idx)

    blobs, views, off = [b_pos, b_nrm, b_uv, b_idx, png], [], 0
    for i, b in enumerate(blobs):
        views.append({"buffer": 0, "byteOffset": off, "byteLength": len(b)})
        if i < 4:
            views[-1]["target"] = 34963 if i == 3 else 34962
        off += len(pad(b))
    bin_chunk = b"".join(pad(b) for b in blobs)

    lo = [min(v[k] for v in pos) for k in range(3)]
    hi = [max(v[k] for v in pos) for k in range(3)]
    gltf = {
        "asset": {"version": "2.0", "generator": "tools/make-dice.py"},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"mesh": 0, "name": "die"}],
        "meshes": [{"name": "die", "primitives": [
            {"attributes": {"POSITION": 0, "NORMAL": 1, "TEXCOORD_0": 2},
             "indices": 3, "material": 0}]}],
        "accessors": [
            {"bufferView": 0, "componentType": 5126, "count": len(pos), "type": "VEC3",
             "min": lo, "max": hi},
            {"bufferView": 1, "componentType": 5126, "count": len(nrm), "type": "VEC3"},
            {"bufferView": 2, "componentType": 5126, "count": len(uv), "type": "VEC2"},
            {"bufferView": 3, "componentType": 5123, "count": len(idx), "type": "SCALAR"},
        ],
        "bufferViews": views,
        "buffers": [{"byteLength": len(bin_chunk)}],
        "materials": [{"name": "die", "pbrMetallicRoughness": {
            "baseColorTexture": {"index": 0}, "metallicFactor": 0.0, "roughnessFactor": 0.85}}],
        "textures": [{"source": 0, "sampler": 0}],
        "images": [{"bufferView": 4, "mimeType": "image/png"}],
        # CLAMP_TO_EDGE on both axes: the atlas packs six faces, so a wrapping sampler would
        # bleed one face's border into the next at the bevel.
        "samplers": [{"magFilter": 9729, "minFilter": 9987, "wrapS": 33071, "wrapT": 33071}],
    }
    js = pad(json.dumps(gltf, separators=(",", ":")).encode("utf-8")).replace(b"\x00", b" ")
    out = (struct.pack("<III", 0x46546C67, 2, 12 + 8 + len(js) + 8 + len(bin_chunk))
           + struct.pack("<II", len(js), 0x4E4F534A) + js
           + struct.pack("<II", len(bin_chunk), 0x004E4942) + bin_chunk)
    open(path, "wb").write(out)
    return len(out)


# ---------------------------------------------------------------------------------------------
# Verification — counted off the finished pixels, not off the table that drew them
# ---------------------------------------------------------------------------------------------
def count_pips(aw, ah, atlas, cell, light):
    """Flood-fill the dark blobs in each atlas cell. Deliberately independent of PIPS: this is
    what turns 'the layout table says 6' into 'the texture holds six dots'."""
    found = {}
    for value in range(1, 7):
        col, row = (value - 1) % 3, (value - 1) // 3
        ox, oy = col * cell, row * cell
        thr = (light[0] + light[1] + light[2]) / 3.0 * 0.72
        mask = bytearray(cell * cell)
        for y in range(cell):
            for x in range(cell):
                o = ((oy + y) * aw + ox + x) * 3
                lum = (atlas[o] + atlas[o + 1] + atlas[o + 2]) / 3.0
                mask[y * cell + x] = 1 if lum < thr else 0
        blobs, seen = 0, bytearray(cell * cell)
        for y in range(cell):
            for x in range(cell):
                if not mask[y * cell + x] or seen[y * cell + x]:
                    continue
                stack, area = [(x, y)], 0
                seen[y * cell + x] = 1
                while stack:
                    px, py = stack.pop()
                    area += 1
                    for nx, ny in ((px + 1, py), (px - 1, py), (px, py + 1), (px, py - 1)):
                        if 0 <= nx < cell and 0 <= ny < cell and mask[ny * cell + nx] \
                                and not seen[ny * cell + nx]:
                            seen[ny * cell + nx] = 1
                            stack.append((nx, ny))
                if area > (cell * 0.02) ** 2:           # ignore grain speckle in the wood
                    blobs += 1
        found[value] = blobs
    return found


def verify_glb(path, cell):
    """Re-open the finished GLB and prove the mapping from its own bytes.

    The atlas check above only says the texture holds the right dots. This says the right dot
    lands on the right face, which is the part a layout table cannot promise: it walks the
    POSITION/TEXCOORD accessors, finds the vertex sitting dead centre of each face, follows its
    UV into the atlas cell it actually samples, and counts the pips in that cell from the PNG
    embedded in the file. Winding is checked at the same time — a face wound inside-out is
    invisible from the front and would otherwise ship.
    """
    import json

    blob = open(path, "rb").read()
    _magic, _ver, _ln = struct.unpack("<III", blob[:12])
    pos = 12
    js = bin_ = None
    while pos < len(blob):
        clen, ctype = struct.unpack("<II", blob[pos:pos + 8])
        body = blob[pos + 8:pos + 8 + clen]
        pos += 8 + clen
        if ctype == 0x4E4F534A:
            js = json.loads(body.decode("utf-8"))
        elif ctype == 0x004E4942:
            bin_ = body
    g = js

    def view(i):
        v = g["bufferViews"][i]
        off = v.get("byteOffset", 0)
        return bin_[off:off + v["byteLength"]]

    def acc(i, fmt, n):
        a = g["accessors"][i]
        raw = view(a["bufferView"])
        return [struct.unpack_from(f"<{n}{fmt}", raw, k * n * (4 if fmt == "f" else 2))
                for k in range(a["count"])]

    prim = g["meshes"][0]["primitives"][0]
    P = acc(prim["attributes"]["POSITION"], "f", 3)
    UV = acc(prim["attributes"]["TEXCOORD_0"], "f", 2)
    idx = [v[0] for v in acc(prim["indices"], "H", 1)]

    png = view(g["images"][0]["bufferView"])
    tmp = path + ".verify.png"
    open(tmp, "wb").write(png)
    try:
        aw, ah, atlas = png_read(tmp)
    finally:
        os.remove(tmp)
    counted = count_pips(aw, ah, atlas, cell, median_rgb_flat(aw, ah, atlas))

    rows, bad = [], 0
    for name, value, _r, _u in FACES:
        axis = "XYZ".index(name[1])
        sgn = 1.0 if name[0] == "+" else -1.0
        target = [0.0, 0.0, 0.0]
        target[axis] = sgn * 0.5
        k = min(range(len(P)), key=lambda i: sum((P[i][c] - target[c]) ** 2 for c in range(3)))
        u, v = UV[k]
        col, row = int(u * 3), int(v * 2)
        cellv = row * 3 + col + 1                    # which value that cell holds
        got = counted.get(cellv, -1)
        ok = cellv == value and got == len(PIPS[value])

        # winding: the first triangle touching this face's centre vertex must face outward
        wind = "?"
        for t in range(0, len(idx), 3):
            if k in idx[t:t + 3]:
                a, b, c = (P[idx[t]], P[idx[t + 1]], P[idx[t + 2]])
                e1 = [b[i] - a[i] for i in range(3)]
                e2 = [c[i] - a[i] for i in range(3)]
                cr = [e1[1] * e2[2] - e1[2] * e2[1],
                      e1[2] * e2[0] - e1[0] * e2[2],
                      e1[0] * e2[1] - e1[1] * e2[0]]
                wind = "out" if cr[axis] * sgn > 0 else "IN"
                break
        ok = ok and wind == "out"
        bad += not ok
        rows.append((name, value, cellv, got, wind, ok))
    return rows, bad


def median_rgb_flat(w, h, rgb):
    ch = []
    for c in range(3):
        vals = sorted(rgb[c::3])
        ch.append(vals[len(vals) // 2])
    return tuple(ch)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default=os.path.join(REPO, "assets/dice/raw/face-src.png"),
                    help="blank die face from Scenario")
    ap.add_argument("--out", default=os.path.join(REPO, "assets/dice/models/die.glb"))
    ap.add_argument("--atlas", default=os.path.join(REPO, "assets/dice/raw/atlas.png"),
                    help="the baked atlas, also written out so it can be eyeballed")
    # The generated face is a modelled block, not a flat swatch: it has a bevelled border, a
    # rounded inner corner and a drop shadow down its right and bottom. A square crop that
    # reaches into any of those brings a dark wedge along, which then reads as a seventh pip —
    # which is exactly how --check first caught this. 0.25 is the widest crop with nothing
    # below the pip threshold anywhere inside it, and at a 512 cell it is also 1:1.
    ap.add_argument("--crop", default="0.25,0.25,0.75,0.75",
                    help="x0,y0,x1,y1 as fractions — the flat interior of the source face")
    ap.add_argument("--cell", type=int, default=512, help="pixels per face")
    ap.add_argument("--pip-radius", type=float, default=0.072, help="fraction of the face")
    ap.add_argument("--pip-gap", type=float, default=0.25, help="pip grid spacing, ditto")
    ap.add_argument("--radius", type=float, default=0.10, help="corner roundover, unit cube")
    ap.add_argument("--seg", type=int, default=8, help="grid segments per face side")
    ap.add_argument("--check", action="store_true", help="re-count the pips from the atlas")
    a = ap.parse_args()

    # The die convention, asserted rather than assumed.
    by_axis = {name: v for name, v, _r, _u in FACES}
    for x, y in (("+X", "-X"), ("+Y", "-Y"), ("+Z", "-Z")):
        if by_axis[x] + by_axis[y] != 7:
            sys.exit(f"FACES: {x}={by_axis[x]} and {y}={by_axis[y]} do not sum to 7")
    if (by_axis["+Y"], by_axis["+Z"], by_axis["+X"]) != (1, 2, 3):
        sys.exit("FACES: not right-handed — 1 up and 2 front must put 3 on the right")

    box = tuple(float(v) for v in a.crop.split(","))
    w, h, rgb = png_read(a.src)
    face = crop_resize(w, h, rgb, box, a.cell)
    light = median_rgb(a.cell, face)
    dark = tuple(int(c * 0.30) for c in light)      # keeps the material's hue, drops the value
    print(f"source  {os.path.relpath(a.src, REPO)}  {w}x{h}")
    print(f"face    #{light[0]:02X}{light[1]:02X}{light[2]:02X} "
          f"→ pips #{dark[0]:02X}{dark[1]:02X}{dark[2]:02X}")

    aw, ah, atlas = build_atlas(face, a.cell, a.pip_radius, a.pip_gap, dark)
    os.makedirs(os.path.dirname(a.atlas), exist_ok=True)
    png = png_write(a.atlas, aw, ah, atlas)
    print(f"atlas   {os.path.relpath(a.atlas, REPO)}  {aw}x{ah}  {len(png) / 1024:.0f} KB")

    pos, nrm, uv, idx = rounded_box(0.5, a.radius, a.seg)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    size = write_glb(a.out, pos, nrm, uv, idx, png)
    print(f"mesh    {len(pos)} verts, {len(idx) // 3} tris, unit cube centred on the origin")
    print(f"glb     {os.path.relpath(a.out, REPO)}  {size / 1024:.0f} KB")

    print()
    print("        face  value  pips" + ("  counted" if a.check else ""))
    counted = count_pips(aw, ah, atlas, a.cell, light) if a.check else {}
    bad = 0
    for name, value, _r, _u in FACES:
        line = f"        {name:>4}  {value:>5}  {len(PIPS[value]):>4}"
        if a.check:
            got = counted[value]
            ok = got == len(PIPS[value])
            bad += not ok
            line += f"  {got:>7} {'ok' if ok else 'WRONG'}"
        print(line)
    if a.check and bad:
        sys.exit(f"\n{bad} face(s) do not carry the pips they should")

    if a.check:
        rows, gbad = verify_glb(a.out, a.cell)
        print()
        print("        the shipped GLB, read back:")
        print("        face  wants  samples cell  pips  winding")
        for name, value, cellv, got, wind, ok in rows:
            print(f"        {name:>4}  {value:>5}  {cellv:>12}  {got:>4}  {wind:>7}"
                  f"  {'ok' if ok else 'WRONG'}")
        if gbad:
            sys.exit(f"\n{gbad} face(s) sample the wrong part of the atlas")
        print("\nall six faces verified — atlas pixels, UV mapping and winding")


